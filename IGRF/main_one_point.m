% Single-point magnetic conjugate query script.
% Edit the parameters below, then run this script in MATLAB.

clear
clc

% ---------------- User parameters ----------------
rlat = 78.1;          % input latitude [deg]
rlong = 16;          % input longitude [deg]
altitude_km = 110;    % input altitude [km]
conj_alt_km = 110;    % target conjugate altitude [km]
% -------------------------------------------------

step = struct( ...
    'base', 200, ...
    'segment_remain_km', [2000, 1000, 500, 200, 50], ...
    'segment_multipliers', [4.0, 2.5, 1.5, 1.0, 0.5, 0.25], ...
    'min_abs', 1, ...
    'max_abs', 1000, ...
    'polar_time_limit_s', 90, ...
    'polar_direct_time_limit_s', 60, ...
    'retry_multipliers', [1, -1, 2, -2], ...
    'small_retry_multipliers', [0.5, -0.5, 0.25, -0.25]);

[conj_lat, conj_lon, conj_alt, b_ratio] = con_mag( ...
    rlat, rlong, altitude_km, conj_alt_km, step);

fprintf('Input point:      lat=%.6f deg, lon=%.6f deg, alt=%.3f km\n', ...
    rlat, rlong, altitude_km);
fprintf('Conjugate point:  lat=%.6f deg, lon=%.6f deg, alt=%.3f km\n', ...
    conj_lat, conj_lon, conj_alt);
fprintf('B_ratio:          %.8f\n', b_ratio);
